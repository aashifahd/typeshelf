#!/usr/bin/env node
// Builds THIRD_PARTY_NOTICES.md from every package that ships inside the app
// (production dependencies only) and checks each licence against an allowlist
// of licences that are compatible with GPL-3.0.
//
//   node scripts/third-party-notices.cjs           write THIRD_PARTY_NOTICES.md
//   node scripts/third-party-notices.cjs --check   fail if it is outdated or a licence is not allowed
'use strict'
const { existsSync, readdirSync, readFileSync, writeFileSync } = require('node:fs')
const { dirname, join } = require('node:path')

const ROOT = join(__dirname, '..')
const OUT = join(ROOT, 'THIRD_PARTY_NOTICES.md')
const ALLOWED = new Set([
  'MIT',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'Apache-2.0',
  'Zlib',
  'CC0-1.0',
  'BlueOak-1.0.0',
  'Unlicense',
  'Python-2.0',
  'MPL-2.0'
])

/** Finds `name` the way Node does: in node_modules of `fromDir`, then each parent. */
function resolveDir(name, fromDir) {
  let dir = fromDir
  for (;;) {
    const candidate = join(dir, 'node_modules', name)
    if (existsSync(join(candidate, 'package.json'))) return candidate
    const parent = dirname(dir)
    if (parent === dir) return null
    dir = parent
  }
}

/** Walks the production dependency tree (dependencies + installed optional ones). */
function listPackages() {
  const seen = new Map()
  const visited = new Set()
  const root = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))
  const queue = Object.keys({ ...root.dependencies, ...root.optionalDependencies }).map((name) => ({ name, from: ROOT, optional: false }))
  for (const name of Object.keys(root.optionalDependencies || {})) queue.find((q) => q.name === name).optional = true
  while (queue.length) {
    const { name, from, optional } = queue.shift()
    const dir = resolveDir(name, from)
    if (!dir) {
      if (optional) continue // e.g. koffi's binaries for other platforms
      throw new Error(`Cannot find dependency ${name} (needed from ${from})`)
    }
    if (visited.has(dir)) continue
    visited.add(dir)
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
    const key = `${pkg.name}@${pkg.version}`
    if (!seen.has(key)) seen.set(key, { dir, pkg })
    for (const dep of Object.keys(pkg.dependencies || {})) queue.push({ name: dep, from: dir, optional: false })
    for (const dep of Object.keys(pkg.optionalDependencies || {})) queue.push({ name: dep, from: dir, optional: true })
  }
  return [...seen.values()].sort((a, b) => a.pkg.name.localeCompare(b.pkg.name) || a.pkg.version.localeCompare(b.pkg.version))
}

function licenseOf(pkg) {
  if (typeof pkg.license === 'string') return pkg.license
  if (pkg.license && pkg.license.type) return pkg.license.type
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type || l).join(' OR ')
  return 'UNKNOWN'
}

/** "(MIT OR Apache-2.0)" is fine if any alternative is allowed; "A AND B" needs all. */
function isAllowed(expr) {
  const clean = expr.replace(/[()]/g, '').trim()
  if (/ OR /.test(clean)) return clean.split(/ OR /).some((p) => isAllowed(p))
  if (/ AND /.test(clean)) return clean.split(/ AND /).every((p) => isAllowed(p))
  return ALLOWED.has(clean)
}

function licenseText(dir) {
  const files = readdirSync(dir).filter((f) => /^(licen[cs]e|copying|notice)(\.|-|$)/i.test(f))
  return files
    .map((f) => readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim())
    .filter(Boolean)
    .join('\n\n')
}

function build(packages) {
  const parts = [
    '# Third-party notices',
    '',
    'Typeshelf is free software licensed under the GNU General Public License v3.0 or later (see LICENSE).',
    'It includes the open-source components listed below. This file is generated by',
    '`npm run notices`; do not edit it by hand.',
    '',
    '## Electron, Chromium and FFmpeg',
    '',
    'The app runs on Electron (MIT). Electron bundles Chromium and other components; their licences ship',
    'next to the app as `LICENSE.electron.txt` and `LICENSES.chromium.html`. Electron also includes',
    '`ffmpeg.dll`, an FFmpeg build licensed under the GNU LGPL v2.1, used as a separate dynamic library.',
    'Its source is available from the Electron project (https://github.com/electron/electron).',
    '',
    '## Fonts',
    '',
    'Typeshelf does not bundle any fonts. Fonts you download through the app come from Google Fonts or',
    'Fontshare under their own licences, which are shown on each family\'s Info tab.',
    '',
    '## npm packages',
    '',
    '| Package | Version | Licence |',
    '| --- | --- | --- |',
    ...packages.map(({ pkg }) => `| ${pkg.name} | ${pkg.version} | ${licenseOf(pkg)} |`),
    ''
  ]
  for (const { dir, pkg } of packages) {
    parts.push(`### ${pkg.name} ${pkg.version}`, '')
    const text = licenseText(dir)
    parts.push(text ? '```text\n' + text + '\n```' : `Licence: ${licenseOf(pkg)} (no licence file in the package)`, '')
  }
  return parts.join('\n')
}

const packages = listPackages()
const bad = packages.filter(({ pkg }) => !isAllowed(licenseOf(pkg)))
if (bad.length) {
  console.error('Licences that are not on the allowlist:')
  for (const { pkg } of bad) console.error(`  ${pkg.name}@${pkg.version}: ${licenseOf(pkg)}`)
  process.exit(1)
}

const content = build(packages)
if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : ''
  if (current !== content) {
    console.error('THIRD_PARTY_NOTICES.md is out of date. Run: npm run notices')
    process.exit(1)
  }
  console.log(`THIRD_PARTY_NOTICES.md is up to date (${packages.length} packages, all licences allowed).`)
} else {
  writeFileSync(OUT, content)
  console.log(`Wrote THIRD_PARTY_NOTICES.md (${packages.length} packages, all licences allowed).`)
}
